/** Har bir bo‘lim elementlarini kartochka uchun yagona ko‘rinishga keltiradi */
export function getSectionItems(sectionId) {
  switch (sectionId) {
    case 'yangiliklar':
      return allNews.map((n) => ({
        id: n.id,
        title: n.title,
        excerpt: n.excerpt,
        image: n.image,
        tag: n.category,
        meta: n.date,
        href: `/yangilik/${n.id}`,
      }))
    case 'asoschilar':
      return founders.map((f) => ({
        id: f.id,
        title: f.name,
        excerpt: f.excerpt,
        image: f.image,
        tag: f.role.split(',')[0],
        meta: f.role,
        avatar: { initials: f.initials, gradient: f.gradient, photo: f.photo },
        href: `/bolim/asoschilar/${f.id}`,
      }))
    case 'blog':
      return blogPosts.map((p) => ({
        id: p.id,
        title: p.title,
        excerpt: p.excerpt,
        image: p.image,
        tag: p.tag,
        meta: `${p.date} · ${p.readTime} daqiqa`,
        date: p.date,
        readTime: p.readTime,
        featured: Boolean(p.featured),
        href: `/bolim/blog/${p.id}`,
      }))
    case 'musobaqalar':
      return competitions.map((c) => ({
        id: c.id,
        title: c.title,
        excerpt: c.excerpt,
        image: c.image,
        tag: c.sport,
        meta: `${c.date} · ${c.location.split(',')[0]}`,
        date: c.date,
        startsAt: c.startsAt,
        kind: c.kind,
        kindLabel: competitionKinds[c.kind],
        statusKey: c.status,
        status: competitionStatus[c.status],
        href: `/bolim/musobaqalar/${c.id}`,
      }))
    case 'reels':
      return reels.map((r) => ({
        id: r.code,
        title: r.title,
        excerpt: `${r.likes} yoqtirish · ${r.comments} izoh`,
        image: r.image,
        tag: r.tag,
        meta: r.date,
        isVideo: true,
        href: `/bolim/reels/${r.code}`,
      }))
    default:
      return []
  }
}
