/** Har bir bo‘lim elementlarini kartochka uchun yagona ko‘rinishga keltiradi */
export function getSectionItems(sectionId) {
  switch (sectionId) {
    case 'yangiliklar':
      return allNews.map((n) => ({
        id: n.id,
        title: n.title,
        excerpt: n.excerpt,
        image: n.image,
        tag: n.category,
        meta: n.date,
        href: `/yangilik/${n.id}`,
      }))
    case 'asoschilar':
      return founders.map((f) => ({
        id: f.id,
        title: f.name,
        excerpt: f.excerpt,
        image: f.image,
        tag: f.role.split(',')[0],
        meta: f.role,
        avatar: { initials: f.initials, gradient: f.gradient, photo: f.photo },
        href: `/bolim/asoschilar/${f.id}`,
      }))
    case 'blog':
      return blogPosts.map((p) => ({
        id: p.id,
        title: p.title,
        excerpt: p.excerpt,
        image: p.image,
        tag: p.tag,
        meta: `${p.date} · ${p.readTime} ${tr('daqiqa')}`,
        date: p.date,
        readTime: p.readTime,
        featured: Boolean(p.featured),
        href: `/bolim/blog/${p.id}`,
      }))
    case 'musobaqalar':
      // Admin paneldagi tadbirlar (bosh sahifadagi «Sport tadbirlari» bilan bir manba)
      return sportEvents.map((e) => {
        const kind = eventKind(e)
        const statusKey = Date.now() > new Date(e.endsAt).getTime() ? 'finished' : 'open'
        const date = `${e.dates.join(' – ')}, ${e.year}`
        return {
          id: e.id,
          title: e.title,
          excerpt: e.excerpt,
          image: e.image,
          tag: tr(e.category),
          meta: `${date} · ${tr(e.location).split(',')[0]}`,
          date,
          startsAt: e.startsAt,
          kind,
          kindLabel: competitionKinds[kind],
          statusKey,
          status: competitionStatus[statusKey],
          href: `/tadbir/${e.id}`,
        }
      })
    case 'reels':
      return reels.map((r) => ({
        id: r.code,
        title: r.title,
        excerpt: tr('{likes} yoqtirish · {comments} izoh', { likes: r.likes, comments: r.comments }),
        image: r.image,
        tag: r.tag,
        meta: r.date,
        isVideo: true,
        href: `/bolim/reels/${r.code}`,
      }))
    default:
      return []
  }
}
